const lookup = new Map<Language, Map<string, StandardRoom>>();
for (const language of ["en", "sv", "ru"] as const) {
  const values = new Map<string, StandardRoom>();
  for (const [room, roomAliases] of Object.entries(aliases[language])) {
    for (const value of roomAliases ?? []) values.set(normalize(value), room as StandardRoom);
  }
  lookup.set(language, values);
}

function normalize(value: string): string {
  return value
    .normalize("NFKC")
    .trim()
    .toLocaleLowerCase()
    .replace(/[_-]+/g, " ")
    .replace(/\s+/g, " ");
}

function parse(value: string, language: Language): { room: StandardRoom; suffix: string } | null {
  const normalized = normalize(value);
  const direct = lookup.get(language)?.get(normalized);
  if (direct) return { room: direct, suffix: "" };
  const numbered = /^(.*?)(?:\s+(?:#|№|no\.?\s*)?)(\d+)$/.exec(normalized);
  if (!numbered) return null;
  const room = lookup.get(language)?.get(numbered[1].trim());
  return room ? { room, suffix: ` ${numbered[2]}` } : null;
}

/** Translates a recognized whole room name without guessing at user-authored names. */
export function standardRoomName(
  value: string,
  sourceLanguage: Language,
  targetLanguage: Language,
): string | null {
  const parsed = parse(value, sourceLanguage);
  if (!parsed) return null;
  return `${labels[parsed.room]({}, { locale: targetLanguage })}${parsed.suffix}`;
}

/** Returns known aliases in every supported language for localized room-name search. */
export function standardRoomSearchNames(value: string, sourceLanguage: Language): string[] {
  const parsed = parse(value, sourceLanguage);
  if (!parsed) return [];
  const values = new Set<string>();
  for (const language of ["en", "sv", "ru"] as const) {
    values.add(`${labels[parsed.room]({}, { locale: language })}${parsed.suffix}`);
    for (const roomAlias of aliases[language][parsed.room] ?? []) {
      values.add(`${roomAlias}${parsed.suffix}`);
    }
  }
  return [...values];
}
